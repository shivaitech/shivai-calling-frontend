/** Industries matching a search, on their own name or any of their sub-industries
 * ("yoga" finds Fitness, "dentist" finds Dental). Each typed word matches on its
 * first 4 letters. "Other" always stays so there's a way out. */
export function searchIndustries(query: string): IndustryOption[] {
  const tokens = query.toLowerCase().split(/\s+/).filter(Boolean).map((t) => t.slice(0, 4));
  if (!tokens.length) return AGENT_INDUSTRIES;
  return AGENT_INDUSTRIES.filter((ind) => {
    if (ind.value === "other") return true;
    const haystack = [ind.label, ...(AGENT_SUB_INDUSTRIES[ind.value] ?? []).map((s) => s.label)]
      .join(" ")
      .toLowerCase();
    return tokens.every((t) => haystack.includes(t));
  });
}

/** Business-profile industry picker (sub-tenants): stores the label itself, as
 * those records always have. A saved value that's no longer listed (e.g. the old
 * "Retail / E-commerce") is kept as an option so it still shows. */
export function industryLabelOptions(current?: string): { value: string; label: string }[] {
  const options = AGENT_INDUSTRIES.map((i) => ({ value: i.label, label: `${i.icon} ${i.label}` }));
  if (current && !options.some((o) => o.value === current)) options.unshift({ value: current, label: current });
  return options;
}

export const industryLabel = (value: string): string =>
  AGENT_INDUSTRIES.find((i) => i.value === value)?.label ?? value;
